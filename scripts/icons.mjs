// Regenerates every derived brand asset from branding/*.svg and brand.json:
//   src-tauri/icons/*        Linux and macOS app icons (tauri icon, from branding/icon.svg)
//   public/logo.svg          boot-screen logo (copy of branding/icon.svg)
//   public/favicon.svg       small-size icon (copy of branding/favicon.svg)
//   public/favicon-32x32.png, public/icon.png
//   branding/wordmark*.svg   mark + name, dark and light (from brand.json wordmark)
//   branding/social.svg/png  1280×640 repository social preview
// Run after editing branding/ or renaming in brand.json: `npm run icons`.
import { copyFileSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync, spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const at = (path) => join(root, path);
const brand = JSON.parse(readFileSync(at('brand.json'), 'utf8'));
const tauri = (...args) => execFileSync('npx', ['--no-install', 'tauri', ...args], { cwd: root, stdio: 'inherit' });

// Mark geometry shared by the generated SVGs (24-unit grid, see branding/mark.svg).
const MARK = `<path d="M7 7.4V19.6M7 13.6a5 5 0 0 1 10 0v2.2"/>
    <circle cx="7" cy="4.3" r="1.9" fill="currentColor" stroke="none"/>
    <circle cx="17" cy="19.2" r="1.9" fill="currentColor" stroke="none"/>`;
const escape = (s) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const [strong, muted = ''] = brand.wordmark ?? [brand.slug];
const FONT = "Inter, 'SF Pro Display', 'Segoe UI', system-ui, sans-serif";

console.log('icons: platform icons');
tauri('icon', 'branding/icon.svg', '-o', 'src-tauri/icons');
// `tauri icon` also writes Windows, Android and iOS icons; only Linux and macOS ship.
for (const path of ['icon.ico', 'StoreLogo.png', 'android', 'ios']) {
  rmSync(at(`src-tauri/icons/${path}`), { recursive: true, force: true });
}
for (const file of readdirSync(at('src-tauri/icons'))) {
  if (/^Square\d+x\d+Logo\.png$/.test(file)) rmSync(at(`src-tauri/icons/${file}`));
}

console.log('icons: web assets');
copyFileSync(at('branding/icon.svg'), at('public/logo.svg'));
copyFileSync(at('branding/favicon.svg'), at('public/favicon.svg'));
copyFileSync(at('src-tauri/icons/128x128@2x.png'), at('public/icon.png'));
const scratch = mkdtempSync(join(tmpdir(), `${brand.slug}-icons-`));
try {
  tauri('icon', 'branding/favicon.svg', '-o', scratch, '-p', '32');
  copyFileSync(join(scratch, '32x32.png'), at('public/favicon-32x32.png'));
} finally {
  rmSync(scratch, { recursive: true, force: true });
}

console.log('icons: wordmark and social preview');
// Dark and light wordmarks (README uses <picture> to pick one per theme).
for (const [file, ink, text, dim] of [
  ['wordmark.svg', '#b8f58e', '#eceee9', '#8f968c'],
  ['wordmark-light.svg', '#497933', '#202624', '#737b7a'],
]) {
  writeFileSync(at(`branding/${file}`), `<!-- Generated by scripts/icons.mjs from brand.json; do not edit. -->
<svg xmlns="http://www.w3.org/2000/svg" width="340" height="96" viewBox="0 0 340 96">
  <g transform="translate(2 10) scale(3.25)" fill="none" stroke="${ink}" stroke-width="2.3" stroke-linecap="round" color="${ink}">
    ${MARK}
  </g>
  <text x="80" y="66" font-family="${FONT}" font-size="52" font-weight="650" letter-spacing="-1.5" fill="${text}">${escape(strong)}<tspan fill="${dim}">${escape(muted)}</tspan></text>
</svg>
`);
}
const social = `<!-- Generated by scripts/icons.mjs from brand.json; do not edit. -->
<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="640" viewBox="0 0 1280 640">
  <defs>
    <radialGradient id="glow" cx="330" cy="300" r="520" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#b8f58e" stop-opacity=".14"/><stop offset="1" stop-color="#b8f58e" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="1280" height="640" fill="#101113"/>
  <rect width="1280" height="640" fill="url(#glow)"/>
  <g transform="translate(120 152) scale(14)" fill="none" stroke="#b8f58e" stroke-width="2.3" stroke-linecap="round" color="#b8f58e">
    ${MARK}
  </g>
  <text x="520" y="300" font-family="${FONT}" font-size="120" font-weight="650" letter-spacing="-4" fill="#eceee9">${escape(strong)}<tspan fill="#8f968c">${escape(muted)}</tspan></text>
  <text x="524" y="370" font-family="${FONT}" font-size="30" fill="#a2a79e">Coding-agent sessions from this machine</text>
  <text x="524" y="412" font-family="${FONT}" font-size="30" fill="#a2a79e">and every SSH host, in one searchable place.</text>
</svg>
`;
writeFileSync(at('branding/social.svg'), social);
// PNG export needs a system rasterizer; GitHub's social preview requires PNG/JPG.
if (spawnSync('rsvg-convert', ['--version']).status === 0) {
  execFileSync('rsvg-convert', [at('branding/social.svg'), '-o', at('branding/social.png')]);
} else {
  console.warn('icons: rsvg-convert not found; branding/social.png not refreshed');
}
console.log('icons: done');
